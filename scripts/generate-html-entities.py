#!/usr/bin/env python3
"""Regenerate the XML-safe HTML named character references that the reader, text
extraction and the viewer share.

Fetch https://html.spec.whatwg.org/entities.json to a local file, then run:
    python3 scripts/generate-html-entities.py /path/to/entities.json

Only semicolon-terminated spellings are included: XML requires the semicolon.
The source digest in the generated file identifies the exact input snapshot.
"""

import hashlib
import json
from pathlib import Path
import sys


def main():
    source = Path(sys.argv[1]).read_bytes()
    entities = json.loads(source)
    rows = []
    for spelling, entity in sorted(entities.items()):
        if not spelling.endswith(";"):
            continue
        name = spelling[1:-1]
        assert spelling.startswith("&") and name.isascii() and name.isalnum()
        scalars = entity["codepoints"]
        assert scalars and all(0 < scalar <= 0x10FFFF and not 0xD800 <= scalar <= 0xDFFF for scalar in scalars)
        assert "".join(chr(scalar) for scalar in scalars) == entity["characters"]
        numeric = "".join(f"&#{scalar};" for scalar in scalars)
        rows.append(f'        "{name}": "{numeric}",')
    header = (
        "// Generated by scripts/generate-html-entities.py from https://html.spec.whatwg.org/entities.json.\n"
        f"// Source SHA-256: {hashlib.sha256(source).hexdigest()}\n"
        "// The HTML Standard's semicolon-terminated named character references, including\n"
        "// MathML names and references with two scalars. XML requires the semicolon.\n"
        "// Numeric output preserves XML escaping, including ampersands and less-than signs.\n"
        "package enum HTMLNamedCharacterReferences {\n"
        "    package static let numeric: [String: String] = [\n"
    )
    output = Path(__file__).resolve().parents[1] / "Sources/EPUBCore/HTMLNamedCharacterReferences.swift"
    output.write_text(header + "\n".join(rows) + "\n    ]\n}\n")
    print(f"Generated {len(rows)} named references")


if __name__ == "__main__":
    main()
